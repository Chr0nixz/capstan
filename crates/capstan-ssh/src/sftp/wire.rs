use std::io;
use tokio::io::{AsyncRead, AsyncReadExt, AsyncWrite, AsyncWriteExt, DuplexStream};
use tokio_util::{sync::CancellationToken, task::TaskTracker};

pub const MAX_PACKET_BYTES: usize = 256 * 1024;
pub(super) const MAX_DATA_BYTES: usize = 32 * 1024;
const MAX_HANDLE_BYTES: usize = 256;
const PIPE_BYTES: usize = 64 * 1024;

/// Keeps opaque SFTP handles reversible across russh-sftp's UTF-8 String API.
/// Incoming handle bytes become lowercase hex; only handle fields in outgoing
/// requests are decoded. Paths and file contents are never interpreted here.
pub struct SftpWire {
    cancel: CancellationToken,
    tasks: TaskTracker,
}

/// A cache may retain cleanup without retaining the client or its pool lease.
#[derive(Clone)]
pub(crate) struct SftpReaper {
    cancel: CancellationToken,
    tasks: TaskTracker,
}
impl SftpReaper {
    pub(crate) async fn close(&self) {
        self.cancel.cancel();
        self.tasks.wait().await;
    }
}

impl SftpWire {
    pub fn bridge<S>(stream: S) -> (DuplexStream, Self)
    where
        S: AsyncRead + AsyncWrite + Unpin + Send + 'static,
    {
        let (library, bridge) = tokio::io::duplex(PIPE_BYTES);
        let (server_read, server_write) = tokio::io::split(stream);
        let (library_read, library_write) = tokio::io::split(bridge);
        let tasks = TaskTracker::new();
        let cancel = CancellationToken::new();
        for (read, write, incoming) in [
            (
                Box::new(server_read) as Box<dyn AsyncRead + Unpin + Send>,
                Box::new(library_write) as Box<dyn AsyncWrite + Unpin + Send>,
                true,
            ),
            (
                Box::new(library_read) as Box<dyn AsyncRead + Unpin + Send>,
                Box::new(server_write) as Box<dyn AsyncWrite + Unpin + Send>,
                false,
            ),
        ] {
            let cancel = cancel.clone();
            tasks.spawn(async move {
                tokio::select! {
                    biased;
                    () = cancel.cancelled() => {}
                    _ = relay(read, write, incoming) => {}
                }
                cancel.cancel();
            });
        }
        tasks.close();
        (library, Self { cancel, tasks })
    }

    /// Join both owned relay tasks before another subsystem may be opened.
    pub async fn close(&self) {
        self.cancel.cancel();
        self.tasks.wait().await;
    }

    pub fn is_closed(&self) -> bool {
        self.cancel.is_cancelled()
    }
    pub(crate) fn reaper(&self) -> SftpReaper {
        SftpReaper {
            cancel: self.cancel.clone(),
            tasks: self.tasks.clone(),
        }
    }

    pub(crate) fn cancel(&self) {
        self.cancel.cancel();
    }
    pub(crate) async fn cancelled(&self) {
        self.cancel.cancelled().await;
    }
}

impl Drop for SftpWire {
    fn drop(&mut self) {
        self.cancel.cancel();
    }
}

async fn relay<R: AsyncRead + Unpin, W: AsyncWrite + Unpin>(
    mut read: R,
    mut write: W,
    incoming: bool,
) -> io::Result<()> {
    loop {
        let length = read.read_u32().await? as usize;
        // Bounds apply before allocation, also to packets generated by a caller.
        if length == 0 || length > MAX_PACKET_BYTES {
            return Err(invalid_frame());
        }
        let mut frame = vec![0; length];
        read.read_exact(&mut frame).await?;
        transform(&mut frame, incoming)?;
        if frame.len() > MAX_PACKET_BYTES {
            return Err(invalid_frame());
        }
        // The complete frame is already buffered. Keep its prefix and body in
        // one stream write so small metadata requests do not become separate
        // SSH channel messages just for the length prefix. Partial writes still
        // follow AsyncWrite's normal backpressure and cancellation behavior.
        let prefix = (frame.len() as u32).to_be_bytes();
        frame.reserve_exact(prefix.len());
        frame.splice(..0, prefix);
        write.write_all(&frame).await?;
        write.flush().await?;
    }
}

fn invalid_frame() -> io::Error {
    // Never put untrusted packet bytes or decoded paths in error messages.
    io::Error::new(io::ErrorKind::InvalidData, "invalid SFTP frame")
}

fn string_range(frame: &[u8], start: usize) -> io::Result<std::ops::Range<usize>> {
    let prefix = frame
        .get(start..start.checked_add(4).ok_or_else(invalid_frame)?)
        .ok_or_else(invalid_frame)?;
    let length = u32::from_be_bytes(prefix.try_into().map_err(|_| invalid_frame())?) as usize;
    let end = start
        .checked_add(4)
        .and_then(|start| start.checked_add(length))
        .ok_or_else(invalid_frame)?;
    if end > frame.len() {
        return Err(invalid_frame());
    }
    Ok(start + 4..end)
}

fn replace_string(
    frame: &mut Vec<u8>,
    start: usize,
    range: std::ops::Range<usize>,
    replacement: &[u8],
) {
    let mut encoded = (replacement.len() as u32).to_be_bytes().to_vec();
    encoded.extend_from_slice(replacement);
    frame.splice(start..range.end, encoded);
}

fn transform(frame: &mut Vec<u8>, incoming: bool) -> io::Result<()> {
    let kind = *frame.first().ok_or_else(invalid_frame)?;
    // Bound every prefetched reply before handing its body to the library.
    // A per-file window reserves this maximum even if a server advertises a
    // smaller requested length. Frame/SSH transit storage is a separate bound.
    if incoming && kind == 103 {
        let data = string_range(frame, 5)?;
        if data.len() > MAX_DATA_BYTES || data.end != frame.len() {
            return Err(invalid_frame());
        }
    }
    // Bound NAME's advertised vector count before the third-party deserializer
    // can use it as an allocation hint, even for a tiny malicious frame.
    if incoming && kind == 104 {
        let count = frame.get(5..9).ok_or_else(invalid_frame)?;
        if u32::from_be_bytes(count.try_into().map_err(|_| invalid_frame())?) > 256 {
            return Err(invalid_frame());
        }
    }
    let handle_start =
        if (incoming && kind == 102) || (!incoming && matches!(kind, 4 | 5 | 6 | 8 | 10 | 12)) {
            Some(5)
        } else if !incoming && kind == 200 {
            let extension = string_range(frame, 5)?;
            match &frame[extension.clone()] {
                b"fsync@openssh.com" | b"fstatvfs@openssh.com" => Some(extension.end),
                _ => None,
            }
        } else {
            None
        };
    if let Some(start) = handle_start {
        let range = string_range(frame, start)?;
        let value = &frame[range.clone()];
        let transformed = if incoming {
            if value.len() > MAX_HANDLE_BYTES {
                return Err(invalid_frame());
            }
            let mut hex = Vec::with_capacity(value.len() * 2);
            for byte in value {
                hex.push(b"0123456789abcdef"[(byte >> 4) as usize]);
                hex.push(b"0123456789abcdef"[(byte & 15) as usize]);
            }
            hex
        } else {
            if value.len() > MAX_HANDLE_BYTES * 2 || !value.len().is_multiple_of(2) {
                return Err(invalid_frame());
            }
            let digit = |byte: u8| match byte {
                b'0'..=b'9' => Ok(byte - b'0'),
                b'a'..=b'f' => Ok(byte - b'a' + 10),
                _ => Err(invalid_frame()),
            };
            let mut bytes = Vec::with_capacity(value.len() / 2);
            for pair in value.chunks_exact(2) {
                bytes.push((digit(pair[0])? << 4) | digit(pair[1])?);
            }
            bytes
        };
        replace_string(frame, start, range, &transformed);
    }
    // Library errors include server STATUS strings. Strip those strings before
    // parsing to prevent filenames, credentials or file contents in diagnostics.
    if incoming && kind == 101 {
        if frame.len() < 9 {
            return Err(invalid_frame());
        }
        let message = string_range(frame, 9)?;
        let language = string_range(frame, message.end)?;
        if language.end != frame.len() {
            return Err(invalid_frame());
        }
        frame.truncate(9);
        frame.extend_from_slice(&[0; 8]);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[derive(Clone, Default)]
    struct Writes(std::sync::Arc<std::sync::Mutex<Vec<Vec<u8>>>>);
    impl AsyncWrite for Writes {
        fn poll_write(
            self: std::pin::Pin<&mut Self>,
            _: &mut std::task::Context<'_>,
            bytes: &[u8],
        ) -> std::task::Poll<io::Result<usize>> {
            self.0.lock().unwrap().push(bytes.to_vec());
            std::task::Poll::Ready(Ok(bytes.len()))
        }
        fn poll_flush(
            self: std::pin::Pin<&mut Self>,
            _: &mut std::task::Context<'_>,
        ) -> std::task::Poll<io::Result<()>> {
            std::task::Poll::Ready(Ok(()))
        }
        fn poll_shutdown(
            self: std::pin::Pin<&mut Self>,
            _: &mut std::task::Context<'_>,
        ) -> std::task::Poll<io::Result<()>> {
            std::task::Poll::Ready(Ok(()))
        }
    }

    #[tokio::test]
    async fn complete_metadata_frames_are_handed_to_the_stream_in_one_write() {
        for (incoming, kind) in [(false, 1), (true, 2)] {
            let packet = [0, 0, 0, 5, kind, 0, 0, 0, 3];
            let writes = Writes::default();
            let result = relay(packet.as_slice(), writes.clone(), incoming).await;
            assert_eq!(result.unwrap_err().kind(), io::ErrorKind::UnexpectedEof);
            assert_eq!(*writes.0.lock().unwrap(), vec![packet.to_vec()]);
        }
    }

    #[tokio::test]
    async fn complete_frame_writes_preserve_bytes_through_partial_backpressured_writes() {
        let packet = [0, 0, 0, 5, 1, 0, 0, 0, 3];
        let input = packet.repeat(16);
        let expected = input.clone();
        let (write, mut read) = tokio::io::duplex(1);
        let send = async move { relay(input.as_slice(), write, false).await };
        let receive = async move {
            let mut actual = Vec::new();
            read.read_to_end(&mut actual).await.unwrap();
            actual
        };
        let (result, actual) = tokio::time::timeout(std::time::Duration::from_secs(5), async {
            tokio::join!(send, receive)
        })
        .await
        .unwrap();
        assert_eq!(result.unwrap_err().kind(), io::ErrorKind::UnexpectedEof);
        assert_eq!(actual, expected);
    }

    #[test]
    fn prefetched_data_is_bounded_even_when_the_server_ignores_requested_lengths() {
        for length in [MAX_DATA_BYTES, MAX_DATA_BYTES + 1] {
            let mut frame = vec![103, 0, 0, 0, 1];
            frame.extend_from_slice(&(length as u32).to_be_bytes());
            frame.resize(length + 9, 0x5a);
            assert_eq!(
                transform(&mut frame, true).is_ok(),
                length == MAX_DATA_BYTES
            );
        }
        let mut trailing = vec![103, 0, 0, 0, 1, 0, 0, 0, 0, 1];
        assert!(transform(&mut trailing, true).is_err());
    }

    #[test]
    fn malformed_handle_fields_fail_without_echoing_their_contents() {
        for mut frame in [
            vec![102],
            vec![102, 0, 0, 0, 1, 255, 255, 255, 255],
            vec![4, 0, 0, 0, 1, 0, 0, 0, 1, b'x'],
        ] {
            let incoming = frame[0] == 102;
            assert_eq!(
                transform(&mut frame, incoming).unwrap_err().to_string(),
                "invalid SFTP frame"
            );
        }
    }

    #[test]
    fn paths_and_file_data_are_not_transformed() {
        let frame = vec![3, 0, 0, 0, 1, 0, 0, 0, 5, b'/', b'a', b'b', b'c', b'd'];
        let mut actual = frame.clone();
        transform(&mut actual, false).unwrap();
        assert_eq!(actual, frame);
        let frame = vec![103, 0, 0, 0, 1, 0, 0, 0, 2, 255, 128];
        let mut actual = frame.clone();
        transform(&mut actual, true).unwrap();
        assert_eq!(actual, frame);
    }

    #[test]
    fn directory_entry_count_is_bounded_before_library_allocation() {
        let mut frame = vec![104, 0, 0, 0, 1];
        frame.extend_from_slice(&u32::MAX.to_be_bytes());
        assert!(transform(&mut frame, true).is_err());
        frame[5..9].copy_from_slice(&256_u32.to_be_bytes());
        assert!(transform(&mut frame, true).is_ok());
    }
}
